function weeklyReport(store, sales, footfall, seller, note) {
  const lines = [
    `:bar_chart: Weekly report, last week: ${store}`,
    `Sales vs target: ${sales}`,
    `Footfall: ${footfall}`,
    `Top seller: ${seller}`,
  ];
  if (note) lines.push(`Note: ${note}`);
  return lines.join("\n");
}

